public class Esercizio7 {
  public static void main(String[] args) {
    int n1 = 10, n2 = 11;
    if(n1 < n2){
      System.out.println("Il primo numero e' minore del secondo.");
    }
    if(n1 == n2){
      System.out.println("Il primo numero e' uguale al secondo.");
    }else{
      System.out.println("Il primo numero e' maggiore del secondo.");
    }
  }
}
