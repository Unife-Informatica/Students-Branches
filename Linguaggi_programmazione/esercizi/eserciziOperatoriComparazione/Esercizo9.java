public class Esercizo9 {
  public static void main(String[] args) {
    int numero = 10;
    int limiteSup = 100;
    int limiteInf = 5;
    if(numero >= limiteInf && numero <= limiteSup){
      System.out.println("Il numero e' contenuto nell' intervallo.");
    }else{
      System.out.println("Il numero non e' contenuto nell' intervallo.");
    }
  }
}
