public class Servizio {
    int codDipendente;
    double oreDiServizio;
    public Servizio(int codDipendente, double oreDiServizio) {
        this.codDipendente = codDipendente;
        this.oreDiServizio = oreDiServizio;
    }
    public int getCodDipendente() {
        return codDipendente;
    }
    public double getOreDiServizio() {
        return oreDiServizio;
    }
    
}
