public class Servizio {
    int codiceDipendente;
    double oreServizio;
    public Servizio(int codiceDipendente, double oreServizio) {
        this.codiceDipendente = codiceDipendente;
        this.oreServizio = oreServizio;
    }
    public int getCodiceDipendente() {
        return codiceDipendente;
    }
    public double getOreServizio() {
        return oreServizio;
    }
    
}
