public class Servizio{
    private int codImpiegato;
    private double oreServizio;
    public Servizio(int codImpiegato, double oreServizio) {
        this.codImpiegato = codImpiegato;
        this.oreServizio = oreServizio;
    }
    public int getCodImpiegato() {
        return codImpiegato;
    }
    public double getOreServizio() {
        return oreServizio;
    }
    
}